#include "secure_vault.h"
#include "crypto.h"

static const uint8_t seed[32] = {
0xAA,0xBB,0xCC,0xDD,0x11,0x22,0x33,0x44,
0x55,0x66,0x77,0x88,0x99,0x00,0x12,0x34,
0x56,0x78,0x9A,0xBC,0xDE,0xF0,0xAB,0xCD,
0xEF,0x01,0x23,0x45,0x67,0x89,0xAB,0xCD
};

void SV_GetKey(uint8_t *key)
{
    uint8_t buffer[64];
    uint8_t hash[32];

    uint32_t *uid = (uint32_t*)0x1FFF7590;

    memcpy(buffer, seed, 32);
    memcpy(buffer+32, uid, 12);

    CRYPTO_SHA256(buffer, 44, hash);

    memcpy(key, hash, 32);
}



