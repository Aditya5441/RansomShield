/**
 * @file    ecdsa_verify.c
 * @brief   See ecdsa_verify.h.
 *
 * NOTE ON HAL API: written against the common stm32wbxx_hal_pka.h
 * shape (HAL_PKA_ECDSAVerif / PKA_ECDSAVerifInTypeDef /
 * HAL_PKA_ECDSAVerif_IsValidSignature). Field names have shifted
 * between STM32Cube_FW_WB releases - check your installed SDK's
 * stm32wbxx_hal_pka.h against the field names below before building.
 * The earlier draft's `HAL_PKA_ECDSAVerify(pubkey, fw_hash, signature)`
 * 3-argument call was not a real HAL function - ST's PKA ECDSA verify
 * needs the curve parameters and R/S components passed explicitly,
 * which is what this does.
 */
#include "ecdsa_verify.h"
#include "stm32wbxx_hal.h"
#include <string.h>

extern PKA_HandleTypeDef hpka;

/* Same NIST P-256 domain parameters as ecdh.c. Duplicated here (rather
 * than shared) so this file has no dependency on ecdh.c - Secure Boot
 * needs ECDSA verify but not ECDH, so keeping them separate avoids
 * pulling ECDH code into a stage that doesn't use it. */
static const uint8_t P256_PRIME[32] = {
    0xFF,0xFF,0xFF,0xFF,0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
    0x00,0x00,0x00,0x00,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF
};
static const uint8_t P256_A[32] = {
    0xFF,0xFF,0xFF,0xFF,0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
    0x00,0x00,0x00,0x00,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFC
};
static const uint8_t P256_GX[32] = {
    0x6B,0x17,0xD1,0xF2,0xE1,0x2C,0x42,0x47,0xF8,0xBC,0xE6,0xE5,0x63,0xA4,0x40,0xF2,
    0x77,0x03,0x7D,0x81,0x2D,0xEB,0x33,0xA0,0xF4,0xA1,0x39,0x45,0xD8,0x98,0xC2,0x96
};
static const uint8_t P256_GY[32] = {
    0x4F,0xE3,0x42,0xE2,0xFE,0x1A,0x7F,0x9B,0x8E,0xE7,0xEB,0x4A,0x7C,0x0F,0x9E,0x16,
    0x2B,0xCE,0x33,0x57,0x6B,0x31,0x5E,0xCE,0xCB,0xB6,0x40,0x68,0x37,0xBF,0x51,0xF5
};
static const uint8_t P256_ORDER[32] = {
    0xFF,0xFF,0xFF,0xFF,0x00,0x00,0x00,0x00,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,
    0xBC,0xE6,0xFA,0xAD,0xA7,0x17,0x9E,0x84,0xF3,0xB9,0xCA,0xC2,0xFC,0x63,0x25,0x51
};

int ECDSA_VerifyP256(const uint8_t pubkey[ECDSA_PUBKEY_LEN],
                      const uint8_t hash[ECDSA_HASH_LEN],
                      const uint8_t signature[ECDSA_SIGNATURE_LEN])
{
    PKA_ECDSAVerifInTypeDef verify_in = {0};
    HAL_StatusTypeDef status;

    verify_in.primeOrderSize = 32U;
    verify_in.modulusSize    = 32U;
    verify_in.coefSign       = 0;
    verify_in.coefA          = P256_A;
    verify_in.modulus        = P256_PRIME;
    verify_in.basePointX     = P256_GX;
    verify_in.basePointY     = P256_GY;
    verify_in.primeOrder     = P256_ORDER;

    verify_in.pPubKeyCurvePtX = pubkey;
    verify_in.pPubKeyCurvePtY = pubkey + 32;
    verify_in.RSign           = signature;
    verify_in.SSign           = signature + 32;
    verify_in.hash            = hash;

    status = HAL_PKA_ECDSAVerif(&hpka, &verify_in, HAL_MAX_DELAY);
    if (status != HAL_OK) {
        return 0;  // PKA error - fail closed
    }

    return HAL_PKA_ECDSAVerif_IsValidSignature(&hpka) ? 1 : 0;
}
