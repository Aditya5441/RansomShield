def parse_dense1() -> list[float]:
    rows = []
    for line in DENSE1_TEXT.strip().splitlines():
        rows.append([float(x) for x in line.split()])
    if len(rows) != 8 or any(len(r) != 64 for r in rows):
        raise ValueError("dense_1 matrix parse failed")
    flat = []
    for out in range(64):
        for inp in range(8):
            flat.append(rows[inp][out])
    return flat


def load_dense2_npz() -> list[float] | None:
    npz = os.path.join(os.path.dirname(__file__), "model_weights.npz")
    if not os.path.exists(npz):
        return None
    import numpy as np

    data = np.load(npz)
    w = data["dense2_w"]
    if w.shape != (64, 32):
        raise ValueError(f"dense2_w shape {w.shape}")
    flat = []
    for out in range(32):
        for inp in range(64):
            flat.append(float(w[inp, out]))
    return flat


def train_dense2_kernel(epochs: int = 400) -> list[float]:
    """Fit dense_2 kernel with frozen user layers (inference mode, no dropout)."""
    random.seed(42)
    inv_std = [1.0 / math.sqrt(v + EPS) for v in NORM_VAR]
    w1 = parse_dense1()
    w3 = OUT_W[:]
    b1 = DENSE1_B[:]
    b2 = DENSE2_B[:]
    b3 = OUT_B

    w2 = [random.gauss(0, 0.05) for _ in range(64 * 32)]

    def forward(x: list[float], training: bool) -> tuple[list[float], list[float], float]:
        norm = [(x[i] - NORM_MEAN[i]) * inv_std[i] for i in range(8)]
        h1 = []
        for j in range(64):
            s = b1[j]
            base = j * 8
            for i in range(8):
                s += w1[base + i] * norm[i]
            h1.append(max(0.0, s))
        h2 = []
        for j in range(32):
            s = b2[j]
            base = j * 64
            for i in range(64):
                s += w2[base + i] * h1[i]
            h2.append(max(0.0, s))
        z = b3
        for i in range(32):
            z += w3[i] * h2[i]
        p = 1.0 / (1.0 + math.exp(-max(-40.0, min(40.0, z))))
        return h1, h2, p

    def sample_batch(n: int) -> tuple[list[list[float]], list[float]]:
        xs, ys = [], []
        for _ in range(n):
            ransom = random.random() < 0.45
            if not ransom:
                xs.append(
                    [
                        random.uniform(5.0, 5.1),
                        random.uniform(0.01, 0.6),
                        random.uniform(0.05, 3.0),
                        random.uniform(0.0, 0.5),
                        random.uniform(0.0, 0.5),
                        random.uniform(0.5, 10.0),
                        random.uniform(-110.0, -40.0),
                        random.uniform(30.0, 55.0),
                    ]
                )
            else:
                xs.append(
                    [
                        random.uniform(4.8, 5.0),
                        random.uniform(1.2, 3.95),
                        random.uniform(6.0, 20.0),
                        random.uniform(2.0, 5.0),
                        random.uniform(3.0, 6.0),
                        random.uniform(40.0, 150.0),
                        random.uniform(-60.0, 10.0),
                        random.uniform(70.0, 95.0),
                    ]
                )
            ys.append(1.0 if ransom else 0.0)
        return xs, ys

    lr = 0.01
    for epoch in range(epochs):
        xs, ys = sample_batch(64)
        for x, y in zip(xs, ys):
            h1, h2, p = forward(x, False)
            dz = p - y
            dh2 = [0.0] * 32
            for i in range(32):
                dh2[i] = dz * w3[i] * (1.0 if h2[i] > 0 else 0.0)
            for j in range(32):
                if h2[j] <= 0:
                    continue
                base = j * 64
                for i in range(64):
                    w2[base + i] -= lr * dh2[j] * h1[i]
        if epoch % 100 == 0:
            print(f"  dense2 train epoch {epoch}")

    return w2


def fmt_array(name: str, values: list[float], per_line: int = 8) -> str:
    lines = []
    for i in range(0, len(values), per_line):
        chunk = values[i : i + per_line]
        lines.append("    " + ", ".join(f"{v:.8f}f" for v in chunk) + ",")
    return f"static const float {name}[] = {{\n" + "\n".join(lines) + "\n};\n"


